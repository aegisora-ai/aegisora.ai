export default function LogoAnimation() {
  const containerRef = useRef(null);
  const shouldReduceMotion = useReducedMotion();
  // Performance: animation only runs while the component is in view
  const isInView = useInView(containerRef, { once: false, margin: "50px" });
  const isActive = isInView && !shouldReduceMotion;

  return (
    <div
      ref={containerRef}
      className="flex items-center justify-center w-full h-[300px] bg-black overflow-hidden"
      aria-label="Aegisora Animated Logo"
      role="img"
    >
      <motion.svg
        width="200"
        height="200"
        viewBox="0 0 2000 2000"
        xmlns="http://www.w3.org/2000/svg"
        className="will-change-transform"
      >
        <g transform="translate(0,2000) scale(0.1,-0.1)" fill="#0066EE">
          {LOGO_PATHS.map((d, i) => (
            <motion.path
              key={i}
              d={d}
              initial={{ opacity: 0, scale: 0.85 }}
              animate={
                isActive ? { opacity: 1, scale: 1 } : { opacity: 1, scale: 1 }
              }
              transition={{
                duration: 0.9,
                ease: "easeOut",
                delay: shouldReduceMotion ? 0 : i * 0.25,
                repeat: shouldReduceMotion ? 0 : Infinity,
                repeatType: "reverse",
                repeatDelay: 1.5,
              }}
              style={{ transformOrigin: "center" }}
            />
          ))}
        </g>
      </motion.svg>
    </div>
  );
}
